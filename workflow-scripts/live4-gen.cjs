// Builds /tmp/frbench/live4/steps.json from runC-plan.json live_check_4 and generates the workflow
// .claude/worktrees/_wf-scripts/live-check-4.js with its settings built in (const ARGS), so that a relaunch
// after a container restart only needs ARGS.done (saved agent results by label) regenerated.
// Usage: node live4-gen.cjs [done.json]   (done.json: { "<label>": <saved result> })
const fs = require("fs");
const p = JSON.parse(fs.readFileSync("/tmp/frbench/runC-plan.json", "utf8"));
const done = process.argv[2] ? JSON.parse(fs.readFileSync(process.argv[2], "utf8")) : {};

const JOURNEYS = {
  github: { ports: "daemon 49000-49009, UI 2600-2609", 1: ["LC-C1", "LC-C12"], 2: ["LC-C3", "LC-C4"], extra: "GitHub on forerunner-sandbox with the real token (LC-C1, LC-C4) and the bench's fake GitHub (--githost) where a step names bench/seeded." },
  session: { ports: "daemon 49010-49019, UI 2610-2619", 1: ["LC-C17", "LC-C18", "LC-C32", "LC-C2"], 2: ["LC-C19"], extra: "LC-C32 runs in LC-C18's bench home right after LC-C18." },
  pause: { ports: "daemon 49020-49029, UI 2620-2629", 1: ["LC-C7", "LC-C8", "LC-C5"], 2: ["LC-C6", "LC-C9"], extra: "LC-C8 right after LC-C7, LC-C5 after both, in the same bench home." },
  chat: { ports: "daemon 49030-49039, UI 2630-2639", 1: ["LC-C10", "LC-C11", "LC-C13"], 2: ["LC-C14", "LC-C15", "LC-C16"], extra: "" },
  creds: { ports: "daemon 49040-49049, UI 2640-2649", 1: ["LC-C21", "LC-C23", "LC-C24", "LC-C31"], 2: ["LC-C22", "LC-C25"], 3: ["LC-C26"], extra: "Credential steps: read the C5 and C6 reports (runC-C5-*-d1109-cred-engine.json, runC-C6-*-d1109-cred-screens.json) for how the bench plays the subscription and its limit beside the real key; where the bench cannot play a step, say exactly what is missing." },
  selftasks: { ports: "daemon 49050-49059, UI 2650-2659", 1: ["LC-C27", "LC-C29"], 2: ["LC-C28", "LC-C30"], extra: "" },
  l3: { ports: "daemon 49060-49069, UI 2660-2669", 2: ["LC-L3"], extra: "LC-L3 is the last priority 2 step: run only the check_in_the_app items of run L3 that no earlier journey already covered (read the other journeys' step files in /tmp/frbench/live4/*/steps/ first), cheapest first, while the ledger stays under USD 6.30." },
};

const steps = [];
for (const [journey, j] of Object.entries(JOURNEYS)) {
  for (const pass of [1, 2, 3]) {
    for (const id of j[pass] || []) {
      const s = p.live_check_4.steps.find((x) => x.id === id);
      if (!s) throw new Error(`no step ${id}`);
      steps.push({ id, journey, pass, priority: s.priority, est_usd: s.est_usd, step: s.step, source: s.source, needs: s.needs });
    }
  }
}
const all = new Set(steps.map((s) => s.id));
const lead = p.live_check_4.steps.filter((s) => !all.has(s.id)).map((s) => s.id);
if (JSON.stringify(lead) !== JSON.stringify(["LC-C20"])) throw new Error(`unassigned: ${lead}`);
fs.writeFileSync(
  "/tmp/frbench/live4/steps.json",
  JSON.stringify(
    {
      base: "4cf11fdb0a1e10af94d948c6fcf79a89a083cfbb",
      cap_usd: 7.0,
      stop_new_steps_at_usd: 6.3,
      rules: p.live_check_4.rules,
      by_session_lead: { "LC-C20": "Read by the session lead on the Desktop app workflow's window job: run 77 (d133246) bar and title read live during the session; run 80 (4cf11fd) read after C6." },
      steps,
    },
    null,
    1,
  ),
);

const ARGS = {
  base: "4cf11fd",
  checkout: "/home/user/Forerunner/.claude/worktrees/live4-4cf11fd",
  journeys: Object.fromEntries(Object.entries(JOURNEYS).map(([k, j]) => [k, { ports: j.ports, extra: j.extra, passes: [1, 2, 3].filter((n) => (j[n] || []).length).map((n) => ({ pass: n, ids: j[n] })) }])),
  order: { 1: ["github", "session", "pause", "chat", "creds", "selftasks"], 2: ["github", "session", "pause", "chat", "creds", "selftasks", "l3"], 3: ["creds"] },
  done,
};

const script = `export const meta = {
  name: 'live-check-4',
  description: 'Live check 4 at 4cf11fd (run C merged): the journeys with the real model and forerunner-sandbox under one USD 7.00 ledger (priority 1, then 2, then 3), then a skeptical code-level verification of each finding',
  phases: [
    { title: 'Live 1', detail: 'priority 1 steps, journey by journey' },
    { title: 'Live 2', detail: 'priority 2 steps while the ledger is under USD 6.30' },
    { title: 'Live 3', detail: 'priority 3 if money is left' },
    { title: 'Verify', detail: 'confirm each finding against the code, without the real model' },
  ],
}

// Generated by scratchpad/live4-gen.cjs: settings built in.
const ARGS = ${JSON.stringify(ARGS)}

const COMMON = \`You run one journey of LIVE CHECK 4 of Forerunner at \${ARGS.base} (run C merged), with the REAL Claude model and REAL GitHub (forerunner-sandbox). Read FIRST, whole, and follow: /tmp/frbench/live4/BRIEF.md (binding: the cap and the shared ledger, the secrets, the machine rules, the result file per step). Your steps are in /tmp/frbench/live4/steps.json (filter by your journey and pass). Before you start, read your journey's folder /tmp/frbench/live4/<journey>/steps/: a step already recorded there by an earlier agent (a restart stopped it) is not run again; report it as recorded. The checkout is \${ARGS.checkout}.\`

const LIVE_SCHEMA = {
  type: 'object',
  properties: {
    journey: { type: 'string' },
    pass: { type: 'number' },
    benches: { type: 'array', items: { type: 'string' } },
    spend_usd: { type: 'number', description: 'this agent\\'s spend (the sum of its ledger lines)' },
    ledger_total_usd: { type: 'number', description: 'the shared ledger total when you finished' },
    steps: { type: 'array', items: { type: 'object', properties: {
      id: { type: 'string' }, step: { type: 'string' },
      result: { type: 'string', enum: ['pass', 'fail', 'partial', 'not_seen', 'not_possible_here', 'skipped_cap', 'recorded_earlier'] },
      observed: { type: 'string' }, evidence: { type: 'string' }, usd: { type: 'number' },
    }, required: ['id', 'step', 'result', 'observed'] } },
    findings: { type: 'array', items: { type: 'object', properties: {
      id: { type: 'string', description: 'L4-<journey>-<n>' }, severity: { type: 'string', enum: ['blocker', 'major', 'minor', 'words'] },
      title: { type: 'string' }, step: { type: 'string' }, what_the_person_sees: { type: 'string' }, expected: { type: 'string' },
      evidence: { type: 'string' }, repro: { type: 'string' }, suspected_cause: { type: 'string' },
    }, required: ['id', 'severity', 'title', 'step', 'what_the_person_sees', 'expected', 'evidence', 'repro'] } },
    sandbox_prs: { type: 'object', properties: { opened: { type: 'array', items: { type: 'string' } }, closed: { type: 'array', items: { type: 'string' } }, left_open: { type: 'array', items: { type: 'string' } } } },
    owner_checklist_items: { type: 'array', items: { type: 'string' } },
    notes: { type: 'string' },
  },
  required: ['journey', 'pass', 'spend_usd', 'ledger_total_usd', 'steps', 'findings', 'owner_checklist_items'],
}

const VERIFY_SCHEMA = {
  type: 'object',
  properties: {
    id: { type: 'string' },
    real: { type: 'boolean', description: 'true if the code at the base explains the finding or it reproduces on the stand-in bench; false for a misreading, a test artefact or the model alone' },
    model_only: { type: 'boolean', description: 'the app did as designed and the model chose differently (no code fix unless a prompt or brief the app sends made the choice likely)' },
    severity: { type: 'string', enum: ['blocker', 'major', 'minor', 'words', 'none'] },
    root_cause: { type: 'string' },
    where: { type: 'string', description: 'file:line at the base' },
    known_leftover: { type: 'string', description: 'the id of a leftover that already names it (leftovers-L3/C2/C3/C4/C4b-design/C4b/C5/C6.json), or empty' },
    fix_sketch: { type: 'string' },
    failing_test_idea: { type: 'string', description: 'the test at the person\\'s boundary that fails today' },
    area_hint: { type: 'string', description: 'the run C area that owns the code (runC-plan.json areas), or a small fix area' },
    notes: { type: 'string' },
  },
  required: ['id', 'real', 'model_only', 'severity', 'root_cause', 'where', 'fix_sketch', 'failing_test_idea'],
}

const runJourney = (key, pass) => {
  const label = \`live\${pass}:\${key}\`
  if (ARGS.done[label]) return Promise.resolve(ARGS.done[label])
  const j = ARGS.journeys[key]
  const ids = (j.passes.find((x) => x.pass === pass) || { ids: [] }).ids
  if (!ids.length) return Promise.resolve(null)
  const rule = pass === 1
    ? 'This is pass 1: your priority 1 steps, in this order: ' + ids.join(', ') + '. Check the ledger before each; never start one that would take it past USD 7.00.'
    : pass === 2
      ? 'This is pass 2: your priority 2 steps, in this order: ' + ids.join(', ') + '. Start a step only while the ledger total is under USD 6.30 and the step\\'s estimate keeps it under USD 7.00; otherwise report it skipped_cap.'
      : 'This is pass 3 (priority 3): ' + ids.join(', ') + ', only if the ledger total is under USD 6.30.'
  return agent(\`\${COMMON}
Your journey: \${key}. Your ports: \${j.ports}. \${j.extra}
\${rule}
Before you finish: stop every bench you started (keep its home for later steps or passes that use it), close every pull request on forerunner-sandbox you opened and left open (say which), and make sure every step you ran has its result file.\`, { label, phase: 'Live ' + pass, schema: LIVE_SCHEMA })
}

const live = []
for (const pass of [1, 2, 3]) {
  phase('Live ' + pass)
  const keys = ARGS.order[pass]
  const out = await pipeline(keys, (key) => runJourney(key, pass))
  out.forEach((r, i) => { if (r) live.push(r); else if (ARGS.journeys[keys[i]].passes.find((x) => x.pass === pass)) log(\`no result for live\${pass}:\${keys[i]}\`) })
}

phase('Verify')
const findings = live.flatMap((r) => (r.findings || []).map((f) => ({ ...f, journey: r.journey, pass: r.pass })))
log(\`\${findings.length} findings to verify\`)
const verified = await pipeline(findings, (f) => {
  const label = \`verify:\${f.id}\`
  if (ARGS.done[label]) return Promise.resolve({ finding: f, verdict: ARGS.done[label] })
  return agent(\`You verify one finding of Forerunner's live check 4 against the code at \${ARGS.base} (checkout \${ARGS.checkout}). Read-only: do not edit, commit or push; keep every shell command inside \${ARGS.checkout} or /tmp/frbench. You may run unit tests (one at a time under flock /tmp/frbench/heavy.lock) and the stand-in bench (\\\`node scripts/bench/start.mjs --provider bench\\\` or bench-api) on ports 49090-49099 / UI 2690-2699, stopped when done; never the real model or real GitHub. Read docs/design/core-experience.md for what the person should see, /tmp/frbench/owner-decisions-2026-11-09.md for what the owner decided, /tmp/frbench/runC-plan.json to name the area, and the leftovers files /tmp/frbench/leftovers-{L3,C2,C3,C4,C4b-design,C4b,C5,C6}.json to see whether a known leftover already names it.

The finding (from the \${f.journey} journey, pass \${f.pass}; its evidence is under /tmp/frbench/live4/\${f.journey}/):
\${JSON.stringify(f)}

Decide: is it real (the code explains it, or it reproduces on the stand-in), the model alone (the app did as designed; the model chose differently), or a misreading or test artefact? Give the root cause with file:line, the severity you agree with, a fix sketch, the failing test at the person's boundary, the area it belongs to, and the known leftover's id if one names it. Default to skeptical: if the evidence does not support the claim, say real=false and why.\`, { label, phase: 'Verify', schema: VERIFY_SCHEMA }).then((verdict) => ({ finding: f, verdict }))
})

const spend = live.reduce((a, r) => a + (Number(r.spend_usd) || 0), 0)
return { base: ARGS.base, spend_usd: Math.round(spend * 100) / 100, live, verified: verified.filter(Boolean) }
`;
const out = "/home/user/Forerunner/.claude/worktrees/_wf-scripts/live-check-4.js";
