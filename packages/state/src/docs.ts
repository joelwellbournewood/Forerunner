import { allColumns, COMMON_COLUMNS, type ColumnDef, ENTITIES, type EntityDef } from "./schema.ts";
import { STATUS_GRAPHS } from "./workflow.ts";

/**
 * Renders docs/maintainers/data-model.md from the schema. Deterministic: tables sorted by
 * name, LF line endings, no timestamps, so repeated runs are byte-identical.
 */

function cell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function code(s: string): string {
  return `\`${s}\``;
}

function defaultCell(col: ColumnDef): string {
  if (col.default === undefined) return "";
  return code(JSON.stringify(col.default));
}

function referenceCell(col: ColumnDef): string {
  return col.references ? code(`${col.references.table}.${col.references.column}`) : "";
}

function typeCell(col: ColumnDef): string {
  if (col.enum) return `${col.type} (${col.enum.map((v) => code(v)).join(", ")})`;
  return col.type;
}

function columnsTable(columns: readonly ColumnDef[]): string[] {
  const out = [
    "| Column | Type | Nullable | Default | References | Description |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const col of columns) {
    const description = col.check
      ? `${col.description} Check: ${code(col.check)}.`
      : col.description;
    out.push(
      `| ${code(col.name)} | ${cell(typeCell(col))} | ${col.nullable ? "yes" : "no"} | ${defaultCell(col)} | ${referenceCell(col)} | ${cell(description)} |`,
    );
  }
  return out;
}

function entitySection(entity: EntityDef): string[] {
  const out: string[] = [`### ${entity.table}`, "", entity.description, ""];
  const flags: string[] = [];
  if (entity.envelope) flags.push("Carries the common columns (see Invariants).");
  else flags.push(`No envelope; primary key ${code(entity.primaryKey ?? "id")}.`);
  if (entity.appendOnly) flags.push("Append-only: UPDATE and DELETE are refused by triggers.");
  out.push(flags.join(" "), "");
  out.push(...columnsTable(entity.columns), "");
  if (entity.indexes.length > 0) {
    out.push("Indexes:", "");
    for (const idx of entity.indexes) {
      const kind = idx.unique ? "unique" : "index";
      const where = idx.where ? ` where ${code(idx.where)}` : "";
      out.push(`- ${kind} on (${idx.columns.map(code).join(", ")})${where}`);
    }
    out.push("");
  }
  return out;
}

function graphSection(): string[] {
  const out: string[] = [];
  for (const key of Object.keys(STATUS_GRAPHS).sort()) {
    const graph = STATUS_GRAPHS[key] as Record<string, readonly string[]>;
    out.push(`${code(key)}:`, "");
    for (const from of Object.keys(graph)) {
      const targets = graph[from] ?? [];
      out.push(
        `- ${code(from)} -> ${targets.length ? targets.map(code).join(", ") : "(terminal)"}`,
      );
    }
    out.push("");
  }
  return out;
}

export function renderDataModelDoc(entities: Record<string, EntityDef> = ENTITIES): string {
  const tables = Object.values(entities).sort((a, b) => a.table.localeCompare(b.table, "en"));
  const lines: string[] = [
    "# Data model",
    "",
    "> Generated by `pnpm docs:schema` from `packages/state/src/schema.ts`. Do not edit by hand:",
    "> CI regenerates this file and fails on a diff. Change the schema, add a migration",
    "> (see migrations.md), then run `pnpm docs:schema`.",
    "",
    "## Purpose",
    "",
    "One schema serves the solo SQLite store and the shared Postgres state service. The",
    "TypeScript declaration in `schema.ts` is the single truth: migration v1 is generated from",
    "it, the repositories encode and decode rows from it, and this page is rendered from it.",
    "",
    "## Storage encoding",
    "",
    "| Schema type | SQLite | Postgres | In JavaScript |",
    "| --- | --- | --- | --- |",
    "| text | TEXT | TEXT | string |",
    "| timestamp | TEXT | TEXT | ISO-8601 UTC string (`2026-01-05T08:00:00.000Z`); lexicographic order is time order |",
    "| int | INTEGER | BIGINT | number (safe up to 2^53) |",
    "| money | INTEGER | BIGINT | number of micro-USD (1 USD = 1,000,000); safe up to 2^53, about 9 billion USD |",
    "| real | REAL | DOUBLE PRECISION | number |",
    "| bool | INTEGER 0/1 | BOOLEAN | boolean |",
    "| json | TEXT | JSONB | parsed value |",
    "",
    "Ids are application-generated UUIDv7 strings. SQL is written once with `?` placeholders;",
    "the Postgres adapter rewrites them to `$n`. Enum columns carry a CHECK constraint in both",
    "dialects, so an unknown value is refused by the database, not only by TypeScript.",
    "",
    "## Invariants",
    "",
    "### Common columns",
    "",
    "Every entity table starts with these columns:",
    "",
    ...columnsTable(COMMON_COLUMNS),
    "",
    "Every write sets `updated_at` from the injected Clock and bumps `version`. Updates with an",
    'expected version fail with `ForerunnerError("version_conflict")` when the row moved.',
    "",
    "### Claims",
    "",
    "A task is claimed in one atomic UPDATE: it succeeds only when `claimed_by` is NULL, is the",
    "same agent, or `claim_expires` is in the past, and the task is `ready`, `claimed` or",
    "`in_progress`. The holder renews the claim while working; `expireClaims(now)` returns lapsed",
    "claimed or in-progress tasks to `ready`. Another agent cannot start a claimed task; it gets",
    '`{ ok: false, reason: "held_by" }` and can only message about it.',
    "",
    "### Reasons on plan, task and milestone changes",
    "",
    "Spec B.5: every change to a plan, task or milestone is versioned with author and reason.",
    "`task.reason`, `milestone.reason` and `session.reason` (the session plan) hold the reason for",
    "the last change next to the envelope's `author_agent` / `author_human` and `version`.",
    "`TaskRepo.transition`, `MilestoneRepo.change` and `SessionRepo.setPlan` take the reason and",
    "the actor as arguments; a milestone insert or update, or a session insert or patch that",
    "carries a `plan` (anything but the empty placeholder `{}` or `[]`), without a non-blank",
    'reason and an author is refused with `ForerunnerError("validation")` on every write path',
    "(`insert`, `insertMany`, `update` and `patch` included), so a caller cannot skip them. A",
    "session inserted without a plan needs none: the runner writes the plan later, with its",
    "reason, through `setPlan`.",
    "",
    "### Findings block close",
    "",
    '`task.transition(..., "done")` is refused with `ForerunnerError("findings_open")` while the task',
    "has findings in status `open`.",
    "",
    "### Decisions stay in their project",
    "",
    '`DecisionRepo.supersede(oldId, input)` refuses with `ForerunnerError("validation")` when the',
    "older decision belongs to another project than the new one, so a caller allowed to record",
    "in one project cannot retire a decision of another by naming its id.",
    "",
    "### Append-only tables",
    "",
    `${Object.values(entities)
      .filter((e) => e.appendOnly)
      .map((e) => code(e.table))
      .sort()
      .join(", ")} accept inserts only. Their repositories expose no update or delete, and`,
    "database triggers refuse UPDATE and DELETE in both dialects.",
    "",
    "### Money and caps",
    "",
    "`cost_ledger` is the truth for every cap. `budget_window` is a cache for fast checks: `ok`",
    "below 80% of the cap, `warn80` from 80%, `stopped` at 100%; a cap of 0 means no cap.",
    "",
    "### Status graphs",
    "",
    ...graphSection(),
    "## Tables",
    "",
  ];
  for (const entity of tables) lines.push(...entitySection(entity));
  lines.push(
    "## Changing the schema",
    "",
    "Edit `packages/state/src/schema.ts`, add a migration under `packages/state/src/migrations/`",
    "(both dialects), run `pnpm docs:schema`, and update `docs/maintainers/migrations.md` if the",
    "procedure changed. `packages/state/test/schema.test.ts` fails when migration v1 no longer",
    "matches the generator or when this file is stale.",
    "",
  );
  return `${lines.join("\n").replace(/\r?\n/g, "\n").replace(/\n+$/, "")}\n`;
}

/** Column count per table, handy for tests and reports. */
export function schemaSummary(
  entities: Record<string, EntityDef> = ENTITIES,
): { table: string; columns: number }[] {
  return Object.values(entities)
    .map((e) => ({ table: e.table, columns: allColumns(e).length }))
    .sort((a, b) => a.table.localeCompare(b.table, "en"));
}
