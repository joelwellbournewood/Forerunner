import { describe, expect, it } from "vitest";
import { parseRequirements } from "../packages/runtime/src/voice/install.ts";
import { lockedPins, torchHashes, torchRequirementText } from "./voice-lock.ts";

/**
 * scripts/voice-lock.ts (ADR 0090) regenerates the voice pins: torch alone with the hashes of
 * its Windows and Linux wheels from the PyTorch index page, the hashed universal locks (uv), and
 * the Requires-Python table. Its network-free parts are tested here.
 */
const PAGE = `
<a href="/whl/cu128/torch-2.11.0%2Bcu128-cp312-cp312-manylinux_2_28_x86_64.whl#sha256=${"a".repeat(64)}">x</a>
<a href="/whl/cu128/torch-2.11.0%2Bcu128-cp312-cp312-win_amd64.whl#sha256=${"b".repeat(64)}">x</a>
<a href="/whl/cu128/torch-2.11.0%2Bcu128-cp311-cp311-win_amd64.whl#sha256=${"c".repeat(64)}">x</a>
<a href="/whl/cu128/torch-2.10.0%2Bcu128-cp312-cp312-win_amd64.whl#sha256=${"d".repeat(64)}">x</a>
<a href="/whl/cu128/torch-2.11.0%2Bcu128-cp312-cp312-manylinux_2_28_aarch64.whl#sha256=${"e".repeat(64)}">x</a>
`;

describe("voice-lock", () => {
  it("takes the cp312 Windows and Linux x86_64 wheels of the pinned version only", () => {
    expect(torchHashes(PAGE, "2.11.0+cu128")).toEqual(["a".repeat(64), "b".repeat(64)]);
  });

  it("refuses when a platform's wheel is missing from the index", () => {
    expect(() => torchHashes(PAGE, "2.10.0+cu128")).toThrow(/manylinux_2_28_x86_64/);
  });

  it("writes torch alone, exact and hashed, in a form the installer parses", () => {
    const text = torchRequirementText("gpu", "2.11.0+cu128", ["a".repeat(64), "b".repeat(64)]);
    const reqs = parseRequirements(text);
    expect(reqs).toEqual([
      {
        name: "torch",
        version: "2.11.0+cu128",
        exact: true,
        url: null,
        marker: null,
        hashes: ["a".repeat(64), "b".repeat(64)],
      },
    ]);
    expect(text).toMatch(/generated by scripts\/voice-lock\.ts/);
  });

  it("lists the name==version pins of a lock for the Requires-Python table", () => {
    const lock = `numpy==2.5.4 \\\n    --hash=sha256:${"a".repeat(64)}\n    # via kokoro\ntriton==3.6.0 ; sys_platform == 'linux' \\\n    --hash=sha256:${"b".repeat(64)}\nen-core-web-sm @ https://x/en_core_web_sm-3.8.0-py3-none-any.whl#sha256=${"c".repeat(64)} \\\n    --hash=sha256:${"c".repeat(64)}\n`;
    expect(lockedPins(lock)).toEqual(["numpy==2.5.4", "triton==3.6.0"]);
  });
});
